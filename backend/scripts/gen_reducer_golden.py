"""Record shared/golden/reducer.json from a real scripted match.

The events are exactly what player 1's socket received; each checkpoint holds
the server's own state after a command (HP, status, hand, charges). Vitest
feeds the events to the client reducer and checks it reaches the same state,
so the vectors compare the client against the server, not against itself.

    python scripts/gen_reducer_golden.py      (from backend/)
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
os.environ["ENV"] = "test"
os.environ["DATABASE_URL"] = f"sqlite:///{tempfile.mkdtemp()}/golden.db"

from app.core.clock import FakeClock  # noqa: E402
from app.core.config import SHARED_DIR  # noqa: E402
from app.main import build_context  # noqa: E402
from app.realtime.hub import Connection  # noqa: E402
from app.seed import seed  # noqa: E402
from tests.engine.conftest import FakeWS, make_player  # noqa: E402


async def main() -> None:
    seed(demo_users=False)
    clock = FakeClock(wall_start_ms=1_790_000_000_000)
    ctx = build_context(clock)
    await ctx.problems.reload()
    await ctx.pool.start()
    p1, p2 = make_player(1250, "golden_one"), make_player(1250, "golden_two")
    actor = await ctx.matches.create_match("ranked", "bit", p1, p2, seed=2024)
    ws = {1: FakeWS(), 2: FakeWS()}
    checkpoints: list[dict] = []

    def checkpoint(label: str) -> None:
        m = actor.m
        checkpoints.append({
            "label": label,
            "after": len(ws[1].sent),
            "expect": {
                "status": "finished" if m.status == "finished" else "aborted" if m.status == "aborted" else m.status,
                "hp": {"1": m.player1_hp, "2": m.player2_hp},
                "hand": [s for s in actor.hands[1].slots],
                "charges": {"blocks": m.player1_blocks_left, "hints": m.player1_hints_left, "rerolls": m.player1_rerolls_left},
                "inflight": actor.rt[1].inflight is not None,
                "you": 1,
            },
        })

    async def settle() -> None:
        await actor.settle()

    async def advance(s: float) -> None:
        for _ in range(int(s * 2)):
            clock.advance(0.5)
            await settle()

    for side in (1, 2):
        await actor.send("join", side, {"conn": Connection(ws[side], 0), "last_seq": 0})
    checkpoint("joined")
    await advance(3.1)
    checkpoint("live")
    tier = lambda n, t: list(actor.hands[n].tiers).index(t)  # noqa: E731
    await actor.send("submit", 1, {"slot": tier(1, 2), "code": "# VERDICT: AC\n# DELAY_MS: 0\n", "language": "python"}, "g1")
    await settle()
    checkpoint("p1 hits with a tier-2 card")
    await advance(2)
    checkpoint("card re-dealt")
    await actor.send("hint", 1, {"slot": tier(1, 1)}, "g2")
    checkpoint("hint")
    await actor.send("block", 1, {}, "g3")
    checkpoint("block")
    await actor.send("submit", 2, {"slot": tier(2, 3), "code": "# VERDICT: AC\n# DELAY_MS: 0\n", "language": "python"}, "g4")
    await settle()
    checkpoint("p2 hit is blocked")
    await advance(2)
    await actor.send("submit", 1, {"slot": tier(1, 3), "code": "# VERDICT: WA 2\n# DELAY_MS: 0\n", "language": "python"}, "g5")
    await settle()
    checkpoint("p1 backfires")
    await advance(20)
    checkpoint("shield expired and timers")
    await actor.send("submit", 2, {"slot": tier(2, 1), "code": "# VERDICT: AC\n# DELAY_MS: 0\n", "language": "python"}, "g6")
    await settle()
    checkpoint("p2 hits")
    await advance(4)
    await actor.send("submit", 1, {"slot": tier(1, 4), "code": "# VERDICT: AC\n# DELAY_MS: 0\n", "language": "python"}, "g7")
    await settle()
    checkpoint("p1 KO")
    out = {"_comment": "generated by backend/scripts/gen_reducer_golden.py from a real scripted match; checkpoints are the server's state",
           "events": ws[1].sent, "checkpoints": checkpoints}
    (SHARED_DIR / "golden" / "reducer.json").write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {len(ws[1].sent)} events and {len(checkpoints)} checkpoints")
    await ctx.matches.shutdown()
    await ctx.pool.stop()


if __name__ == "__main__":
    asyncio.run(main())

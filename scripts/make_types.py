"""Generate frontend/src/net/protocol.generated.ts from the Pydantic protocol models.

    python scripts/make_types.py          # write the file
    python scripts/make_types.py --check  # fail if the committed file is stale
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.realtime import protocol  # noqa: E402

OUT = ROOT / "frontend" / "src" / "net" / "protocol.generated.ts"


def ts_type(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        parts = []
        for s in schema["anyOf"]:
            t = ts_type(s, defs)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    if "const" in schema:
        return f'"{schema["const"]}"'
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(schema.get("items", {}), defs)
        return f"Array<{inner}>"
    if t == "object":
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict):
            return f"Record<string, {ts_type(ap, defs)}>"
        if schema.get("properties"):
            return "{ " + "; ".join(f"{k}: {ts_type(v, defs)}" for k, v in schema["properties"].items()) + " }"
        return "Record<string, unknown>"
    return "unknown"


def interface(name: str, schema: dict, defs: dict) -> str:
    if "enum" in schema:
        return f"export type {name} = {ts_type(schema, defs)};\n"
    req = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, ps in schema.get("properties", {}).items():
        opt = "" if prop in req else "?"
        lines.append(f"  {prop}{opt}: {ts_type(ps, defs)};")
    if schema.get("additionalProperties") is True:
        lines.append("  [key: string]: unknown;")
    lines.append("}\n")
    return "\n".join(lines)


def render() -> str:
    from pydantic import BaseModel

    defs: dict[str, dict] = {}
    roots: dict[str, str] = {}
    for type_name, model in protocol.EVENT_MODELS.items():
        sch = model.model_json_schema(ref_template="#/$defs/{model}")
        for dname, d in sch.pop("$defs", {}).items():
            defs[dname] = d
        defs[model.__name__] = sch
        roots[type_name] = model.__name__
    for alias in ("DamageClass", "Scenario", "Verdict"):
        pass
    out = ["// AUTO-GENERATED by scripts/make_types.py from backend/app/realtime/protocol.py. Do not edit.\n"]
    for name in sorted(defs):
        out.append(interface(name, defs[name], defs))
    out.append("export interface EventDataMap {")
    for t, n in roots.items():
        out.append(f'  "{t}": {n};')
    out.append("}\n")
    out.append("export type EventType = keyof EventDataMap;\n")
    out.append("export interface ServerMessage<T extends EventType = EventType> {\n  v: 1;\n  type: T;\n  seq?: number;\n  t: number;\n  data: EventDataMap[T];\n}\n")
    assert issubclass(protocol.M, BaseModel)
    return "\n".join(out)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run `make types`")
            sys.exit(1)
        print("protocol types are up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
